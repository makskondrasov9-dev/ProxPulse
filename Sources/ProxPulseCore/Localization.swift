    private struct Rule: @unchecked Sendable {
        let regex: NSRegularExpression
        let replacement: String
    }
    private static let rules: [Rule] = english.keys.filter { $0.contains("%@") }.sorted { $0.count > $1.count }.compactMap { key in
        let pattern = "^" + key.components(separatedBy: "%@").map(NSRegularExpression.escapedPattern(for:)).joined(separator: "(.*?)") + "$"
        guard let regex = try? NSRegularExpression(pattern: pattern, options: [.dotMatchesLineSeparators]), let replacement = english[key] else { return nil }
        return Rule(regex: regex, replacement: replacement)
    }
    public static func text(_ source: String, language: String) -> String { translate(source, language: language, depth: 0) }
    private static func translate(_ source: String, language: String, depth: Int) -> String {
        guard language == "en", depth < 4 else { return source }
        if let result = english[source] { return result }
        let ns = source as NSString
        for rule in rules {
            guard let match = rule.regex.firstMatch(in: source, range: NSRange(location: 0, length: ns.length)) else { continue }
            let parts = rule.replacement.components(separatedBy: "%@")
            guard parts.count == match.numberOfRanges else { continue }
            var result = parts[0]
            for index in 1..<parts.count {
                result += translate(ns.substring(with: match.range(at: index)), language: language, depth: depth + 1) + parts[index]
            }
            return result
        }
        let copySuffix = " · скопировать команду"
        if source.hasSuffix(copySuffix) {
            return translate(String(source.dropLast(copySuffix.count)), language: language, depth: depth + 1) + " · copy command"
        }
        // Composite status messages can contain a localized prefix plus an OS error.
        for prefix in ["Данные устарели · ", "Данные устарели. ", "Нет данных · ", "Нет данных. ", "Журнал ноды: "] where source.hasPrefix(prefix) {
            return (english[prefix] ?? prefix) + translate(String(source.dropFirst(prefix.count)), language: language, depth: depth + 1)
        }
        return source
    }
